"""Route declared/registered commands through the engine's original filters and handlers."""
from __future__ import annotations

import copy
import re
from types import SimpleNamespace


def authorized_message(original: str, message: str, effect: str) -> bool:
    """Never use a model-supplied intent/confirmation boolean as write authorization."""
    if effect == "read":
        return True
    return original.strip() in {message, "/" + message, "执行 " + message, "执行：" + message}


def select_entry(snapshot, capability_id: str, message: str):
    if capability_id.startswith("command:"):
        for command in snapshot["commands"]:
            if capability_id == "command:" + command["handler_full_name"]:
                prefix = command["effective_command"]
                if message != prefix and not message.startswith(prefix + " "):
                    raise ValueError("命令已改名或参数不匹配，请重新查询目录。")
                return command["plugin"], command["handler_full_name"], "write"
    for item in snapshot["declarations"]:
        if item["id"] != capability_id or not item.get("handler"):
            continue
        if not re.fullmatch(item["message_pattern"], message):
            raise ValueError("请求不符合此能力声明的消息格式，请参考目录中的示例。")
        return item["plugin"], item["handler"], item["effect"]
    raise ValueError("能力未启用、已移除或没有执行入口，请重新查询目录。")


def clone_event(event, message):
    from astrbot.api.message_components import Plain

    cloned = copy.copy(event)
    cloned.message_obj = copy.copy(event.message_obj)
    cloned.message_obj.message = [Plain(message)] + [
        copy.copy(part) for part in event.get_messages() if not isinstance(part, Plain)
    ]
    cloned.message_obj.message_str = message
    cloned.message_str = message
    cloned._extras = {}
    cloned._result = None
    cloned._force_stopped = False
    cloned._has_send_oper = False
    cloned._temporary_local_files = []
    cloned.call_llm = True  # Never turn an unmatched generated command into another LLM call.
    cloned.is_at_or_wake_command = True
    return cloned


async def execute(context, event, snapshot, capability_id: str, message: str) -> str:
    from astrbot.core.pipeline.context_utils import call_handler
    from astrbot.core.pipeline.waking_check.stage import WakingCheckStage
    from astrbot.core.provider.entities import ProviderRequest
    from astrbot.core.star.star import star_map

    message = message.strip()
    if not message or len(message) > 4000 or "\n" in message or "\r" in message:
        return "请提供一条有效的完整命令（最多 4000 字）。"
    plugin, handler_id, effect = select_entry(snapshot, capability_id, message)
    # The original event is trusted; intent and arguments generated by the LLM are not.
    if not authorized_message(event.get_message_str(), message, effect):
        return f"此操作需要明确确认，请发送：执行 {message}"
    marker = (capability_id, message)
    invoked = event.get_extra("capability_executions")
    if invoked is None:
        invoked = set()
        event.set_extra("capability_executions", invoked)
    if marker in invoked:
        return "本条消息已经提交过这个操作，不再重复执行。"

    cloned = clone_event(event, message)
    stage = WakingCheckStage()
    config = dict(context.get_config(event.unified_msg_origin))
    # The real event already passed wake checks. Catalog messages are exact handler input;
    # don't strip a slash that a legacy regex deliberately includes in its syntax.
    config["wake_prefix"] = []
    await stage.initialize(SimpleNamespace(astrbot_config=config))
    await stage.process(cloned)
    if cloned.is_stopped():
        return "原插件的权限或消息过滤未通过，未执行目标能力。"
    handlers = []
    for handler in cloned.get_extra("activated_handlers", []):
        owner = star_map.get(handler.handler_module_path)
        if owner and owner.name == plugin and handler_id in {
            handler.handler_name, handler.handler_full_name
        }:
            handlers.append(handler)
    if len(handlers) != 1:
        return "原插件未匹配到唯一可执行入口，未执行。请按目录用法发送消息。"
    handler = handlers[0]
    invoked.add(marker)  # Mark before side effects; errors may have occurred after a send.
    params = cloned.get_extra("handlers_parsed_params", {}).get(handler.handler_full_name, {})
    async for response in call_handler(cloned, handler.handler, **params):
        if isinstance(response, ProviderRequest):
            return "此入口需要独立模型会话，请使用插件原命令；不要声称已完成。"
        result = cloned.get_result()
        if result:
            await cloned.send(result)
            cloned.clear_result()
    if cloned._has_send_oper:
        return "目标插件已发送反馈，请以该反馈为准，不要重复发送或推断业务成功。"
    return "已调用目标插件，但没有可确认的发送结果。不要声称操作成功或自动重试。"
